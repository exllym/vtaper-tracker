android {
  namespace = "com.example"
  compileSdk { version = release(36) { minorApiLevel = 1 } }

  defaultConfig {
    applicationId = "com.aistudio.applet.xcbenf"
    minSdk = 26
    targetSdk = 36
    versionCode = 1
    versionName = "1.0"

    testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
  }

  val keystorePropertiesFile = rootProject.file("keystore.properties")
  val debugKeystore = file("${rootDir}/debug.keystore")

  signingConfigs {
    create("release") {
      if (keystorePropertiesFile.exists()) {
        val props = Properties()
        keystorePropertiesFile.inputStream().use { props.load(it) }
        val storePath = props.getProperty("storeFile")?.trim()
        if (!storePath.isNullOrEmpty()) {
          storeFile = rootProject.file(storePath)
        }
        storePassword = props.getProperty("storePassword")
        keyAlias = props.getProperty("keyAlias")
        keyPassword = props.getProperty("keyPassword")
      } else {
        val envKeystorePath = System.getenv("KEYSTORE_PATH")
        val defaultUploadKey = file("${rootDir}/my-upload-key.jks")
        if (!envKeystorePath.isNullOrBlank()) {
          storeFile = file(envKeystorePath)
          storePassword = System.getenv("STORE_PASSWORD")
          keyAlias = "upload"
          keyPassword = System.getenv("KEY_PASSWORD")
        } else if (defaultUploadKey.exists()) {
          storeFile = defaultUploadKey
          storePassword = System.getenv("STORE_PASSWORD")
          keyAlias = "upload"
          keyPassword = System.getenv("KEY_PASSWORD")
        }
      }
    }
    create("debugConfig") {
      storeFile = debugKeystore
      storePassword = "android"
      keyAlias = "androiddebugkey"
      keyPassword = "android"
    }
  }

  buildTypes {
    release {
      isCrunchPngs = false
      isMinifyEnabled = true
      isShrinkResources = true
      isDebuggable = false
      proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
      val releaseSigning = signingConfigs.getByName("release")
      signingConfig = if (releaseSigning.storeFile?.exists() == true) {
        releaseSigning
      } else if (debugKeystore.exists()) {
        signingConfigs.getByName("debugConfig")
      } else {
        signingConfigs.getByName("debug")
      }
    }
    debug {
      if (debugKeystore.exists()) {
        signingConfig = signingConfigs.getByName("debugConfig")
      }
    }
  }
  compileOptions {
    sourceCompatibility = JavaVersion.VERSION_11
    targetCompatibility = JavaVersion.VERSION_11
  }
  buildFeatures {
    compose = true
    buildConfig = true
  }
  testOptions { unitTests { isIncludeAndroidResources = true } }
  dependenciesInfo {
    includeInApk = false
    includeInBundle = true
  }
}

